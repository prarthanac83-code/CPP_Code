public class TestSubstring {
    public static void main(String[] args) {
        String s = "Sachin Tendulkar";
        System.out.println("Original String :" + s);
        System.out.println("Original String starting from 6:" + s.substring(6));
        System.out.println("Original String starting from 0 to 6:" + s.substring(0,6));
    }
}
